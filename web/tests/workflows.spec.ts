import { test, expect, type Page } from '@playwright/test'
test.setTimeout(30000)

const modal = (page: Page) => page.locator('.n-modal:visible')
const row = (page: Page, text: string) => page.locator('tbody tr').filter({ hasText: text })
async function select(page: Page, label: string, option: string) {
  await modal(page).locator('.n-form-item').filter({ has: page.locator('.n-form-item-label', { hasText: new RegExp(`^${label}[\\s*]*$`) }) }).locator('.n-base-selection').click()
  await page.locator('.n-base-select-option').filter({ hasText: option }).first().click()
}
async function fill(page: Page, label: string, value: string) {
  await modal(page).locator('.n-form-item').filter({ has: page.locator('.n-form-item-label', { hasText: new RegExp(`^${label}[\\s*]*$`) }) }).locator('input, textarea').first().fill(value)
}
async function save(page: Page) {
  const saved = page.waitForResponse(res => res.url().includes('/api/v1/') && ['POST', 'PUT'].includes(res.request().method()))
  await modal(page).getByRole('button', { name: 'Save', exact: true }).click()
  const response = await saved
  expect(response.ok(), await response.text()).toBe(true)
  await expect(modal(page)).toHaveCount(0)
}
async function remove(page: Page, name: string) {
  await row(page, name).getByRole('button', { name: 'Delete', exact: true }).click()
  await modal(page).getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(row(page, name)).toHaveCount(0)
  await expect(modal(page)).toHaveCount(0)
}

const errors = new WeakMap<Page, string[]>()
