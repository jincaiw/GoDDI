test('server pagination shows the next page instead of slicing it twice', async ({ page }) => {
  test.setTimeout(60000)
  const prefix = `ui-pages-${Date.now()}`
  await page.goto('/ipam/spaces')
  const headers = await page.evaluate(() => ({ Authorization: `Bearer ${sessionStorage.getItem('token')}`, 'X-CSRF-Token': sessionStorage.getItem('csrf_token') || '' }))
  try {
    for (let i = 0; i < 11; i++) {
      await page.getByRole('button', { name: 'Create Space', exact: true }).click()
      await fill(page, 'Name', `${prefix}-${i}`)
      await save(page)
    }
    await page.locator('.n-pagination .n-base-selection').click()
    await page.locator('.n-base-select-option').filter({ hasText: /^10/ }).click()
    await expect(page.locator('tbody tr')).toHaveCount(10)
    await page.locator('.n-pagination-item').filter({ hasText: /^2$/ }).click()
    await expect(page.locator('tbody tr')).toHaveCount(1)
    await expect(page.locator('tbody tr')).toContainText(prefix)
  } finally {
    const response = await page.request.get('/api/v1/ipam/spaces?page_size=100', { headers })
    for (const space of (await response.json()).data) {
      if (space.name.startsWith(prefix)) await page.request.delete(`/api/v1/ipam/spaces/${space.id}`, { headers })
    }
  }
})

